def ensure_pwa_files():
    """Create /static/manifest.json, service-worker.js and icons if missing."""
    static = Path("static")
    static.mkdir(exist_ok=True)

    manifest = {
        "name": "Family NFL Dashboard",
        "short_name": "NFL Dash",
        "description": "Live NFL scores, power rankings and team stats",
        "start_url": "/",
        "scope": "/",
        "display": "standalone",
        "background_color": "#0A1F44",
        "theme_color": NAVY,
        "icons": [
            {"src": "/app/static/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "/app/static/icon-512.png", "sizes": "512x512", "type": "image/png"},
        ],
    }
    (static / "manifest.json").write_text(json.dumps(manifest, indent=2))

    worker = """
const CACHE = 'nfl-dash-v1';
self.addEventListener('install', e => { self.skipWaiting(); });
self.addEventListener('activate', e => { e.waitUntil(self.clients.claim()); });
// Network-first: live data should never be stale. Falls back to cache if offline.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET') return;
  e.respondWith(
    fetch(e.request).then(res => {
      const copy = res.clone();
      caches.open(CACHE).then(c => c.put(e.request, copy)).catch(() => {});
      return res;
    }).catch(() => caches.match(e.request))
  );
});
"""
    (static / "service-worker.js").write_text(worker.strip())

    if not (static / "icon-512.png").exists():
        try:
            from PIL import Image, ImageDraw

            for size in (192, 512):
                img = Image.new("RGB", (size, size), NAVY)
                d = ImageDraw.Draw(img)
                m = size * 0.14
                d.ellipse([m, size * 0.28, size - m, size * 0.72], fill="#7B3F00")
                d.line([size * 0.36, size * 0.5, size * 0.64, size * 0.5], fill="white", width=max(3, size // 40))
                for i in range(-2, 3):
                    x = size * 0.5 + i * size * 0.06
                    d.line([x, size * 0.44, x, size * 0.56], fill="white", width=max(2, size // 70))
                img.save(static / f"icon-{size}.png")
        except Exception:
            pass


