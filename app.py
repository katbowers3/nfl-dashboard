def render_boxscore(event_id):
    data = fetch_short(f"{ESPN}/summary", (("event", event_id),))
    if not data:
        st.caption("Box score not available yet.")
        return
    box = data.get("boxscore", {})
    for team in box.get("players", []):
        st.markdown(f"**{team['team']['displayName']}**")
        for grp in team.get("statistics", []):
            if grp.get("name") in ("passing", "rushing"):
                labels = grp.get("labels", [])
                rows = []
                for a in grp.get("athletes", []):
                    stats = a.get("stats", [])
                    if len(stats) == len(labels):
                        rows.append([a["athlete"]["displayName"], *stats])
                if rows:
                    st.caption(grp["name"].title())
                    st.dataframe(
                        pd.DataFrame(rows, columns=["Player", *labels]),
                        hide_index=True,
                        use_container_width=True,
                    )
    teams = box.get("teams", [])
    if len(teams) == 2:
        stat_rows = {}
        for t in teams:
            for s in t.get("statistics", []):
                stat_rows.setdefault(s.get("label"), {})[t["team"]["abbreviation"]] = s.get("displayValue")
        if stat_rows:
            st.markdown("**Team stats**")
            st.dataframe(pd.DataFrame(stat_rows).T, use_container_width=True)


@st.fragment(run_every=REFRESH_SECONDS)
def live_dashboard():
    """Everything in here refreshes automatically every 30 seconds."""
    games = load_season_games()
    if games.empty:
        st.warning(
            "Season data didn't load, so rankings and team pages are unavailable. "
            "Retrying automatically. Detail: "
            + st.session_state.get("feed_error", "no response from ESPN")
        )
    else:
        directory = team_directory(games)
        rank = power_rankings(games, directory)
        champion_banner(rank)

    st.subheader("Game Day")
    week_data = fetch_short(f"{ESPN}/scoreboard")
    wk = parse_events(week_data)
    if wk.empty:
        st.info("No games on the current scoreboard.")
    else:
        order = {"in": 0, "pre": 1, "post": 2}
        wk = wk.assign(_o=wk.state.map(order)).sort_values(["_o", "date"])
        n_live = int((wk.state == "in").sum())
        c1, c2, c3 = st.columns(3)
        c1.metric("Live now", n_live)
        c2.metric("Final", int((wk.state == "post").sum()))
        c3.metric("Upcoming", int((wk.state == "pre").sum()))
        for _, g in wk.iterrows():
            game_card(g)
            if g.state in ("in", "post"):
                with st.expander("Passing, rushing & team stats"):
                    render_boxscore(g.id)
    st.caption(
        f"Auto-refreshes every {REFRESH_SECONDS}s · last updated "
        f"{datetime.now(TZ).strftime('%I:%M:%S %p')}"
    )


def cards(items, color):
    html = '<div class="card-grid">' + "".join(
        f'<div class="card" style="--c:{color}"><div class="v">{v}</div><div class="l">{l}</div></div>'
        for l, v in items
    ) + "</div>"
    st.markdown(html, unsafe_allow_html=True)


def team_section(games, directory, rank):
    names = sorted(directory.values(), key=lambda t: t["name"])
    choice = st.selectbox("Pick a team", [t["name"] for t in names])
    team = next(t for t in names if t["name"] == choice)
    abbr, color = team["abbr"], team["color"]

    st.markdown(
        f'<div class="champ" style="background:linear-gradient(135deg,{color},#0A1F44);padding:10px">'
        f'<img src="{team["logo"]}" style="height:56px"/><div class="tname" style="font-size:1.3rem">'
        f"{team['name']}</div></div>",
        unsafe_allow_html=True,
    )

    tg = team_game_rows(games)
    mine = tg[tg.abbr == abbr] if not tg.empty else tg
    if mine.empty:
        st.info("No completed regular-season games yet.")
    else:
        wins, losses = mine[mine.Result == "W"], mine[mine.Result == "L"]
        avg_w = f"{wins.PF.mean():.1f}" if len(wins) else "—"
        avg_l = f"{losses.PF.mean():.1f}" if len(losses) else "—"
        cards(
            [
                ("Wins", len(wins)),
                ("Losses", len(losses)),
                ("Ties", int((mine.Result == "T").sum())),
                ("Avg pts / game", f"{mine.PF.mean():.1f}"),
                ("Avg pts in wins", avg_w),
                ("Avg pts in losses", avg_l),
            ],
            color,
        )
        r = rank[rank.abbr == abbr]
        if not r.empty:
            st.caption(f"Power rank #{int(r.index[0]) + 1} of {len(rank)} · score {r.iloc[0].Power}")

        st.markdown("**Game log**")
        log = mine.sort_values("_date")[["Week", "Date", "Opponent", "Site", "Result", "PF", "PA"]]
        st.dataframe(log, hide_index=True, use_container_width=True)

        fig = go.Figure(
            go.Bar(
                x=[f"W{w}" for w in mine.sort_values("_date").Week],
                y=mine.sort_values("_date").PF,
                marker_color=[
                    color if r_ == "W" else "#777777" for r_ in mine.sort_values("_date").Result
                ],
                name="Points scored",
            )
        )
        fig.update_layout(
            height=240,
            margin=dict(l=0, r=0, t=20, b=0),
            title="Points scored (team color = win, gray = loss)",
            paper_bgcolor="rgba(0,0,0,0)",
            plot_bgcolor="rgba(0,0,0,0)",
            font_color="white",
        )
        st.plotly_chart(fig, use_container_width=True, config={"displayModeBar": False})

    st.markdown("**Upcoming games**")
    nxt = games[(games.state == "pre") & ((games.home == abbr) | (games.away == abbr))].sort_values("date")
    if nxt.empty:
        st.caption("No upcoming games found.")
    else:
        rows = []
        for _, g in nxt.head(6).iterrows():
            is_home = g.home == abbr
            rows.append(
                {
                    "When": g.date.strftime("%a %b %d · %I:%M %p"),
                    "Opponent": ("vs " if is_home else "@ ") + (g.away if is_home else g.home),
                    "Site": "Home" if is_home else "Away",
                    "Weather": game_weather(g),
                }
            )
        st.dataframe(pd.DataFrame(rows), hide_index=True, use_container_width=True)

    st.markdown("**Injured players**")
    inj = load_injuries()
    if inj.empty:
        st.caption("Injury feed unavailable right now.")
    else:
        t_inj = inj[inj.team == team["name"]][["Player", "Pos", "Status", "Note"]]
        if t_inj.empty:
            st.caption("No injuries reported. 🎉")
        else:
            st.dataframe(t_inj, hide_index=True, use_container_width=True)


def schedule_section(games):
    up = games[games.state == "pre"].sort_values("date")
    if up.empty:
        st.info("No upcoming games found.")
        return
    st.caption(f"{len(up)} upcoming games (times in Central).")
    for wk, grp in up.groupby("week", sort=True):
        with st.expander(f"Week {int(wk)}" if pd.notna(wk) else "Other", expanded=(wk == up.week.min())):
            table = pd.DataFrame(
                {
                    "When": grp.date.dt.strftime("%a %b %d · %I:%M %p"),
                    "Away": grp.away,
                    "Home": grp.home,
                    "Weather": [game_weather(g) for _, g in grp.iterrows()],
                }
            )
            st.dataframe(table, hide_index=True, use_container_width=True)


def rankings_section(rank):
    if rank.empty:
        st.info("No data yet.")
        return
    t = rank[["name", "W", "L", "T", "PF", "PA", "Diff", "Power"]].copy()
    t.insert(0, "#", range(1, len(t) + 1))
    t.columns = ["#", "Team", "W", "L", "T", "PF/G", "PA/G", "Margin", "Power"]
    t[["PF/G", "PA/G", "Margin"]] = t[["PF/G", "PA/G", "Margin"]].round(1)
    st.dataframe(t, hide_index=True, use_container_width=True, height=600)


