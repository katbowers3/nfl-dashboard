def team_directory(games):
    d = {}
    for _, g in games.iterrows():
        for s in ("home", "away"):
            d[g[s]] = dict(
                abbr=g[s], name=g[f"{s}_name"], color=g[f"{s}_color"], logo=g[f"{s}_logo"]
            )
    return d


def team_game_rows(games):
    done = games[(games.state == "post") & (games.season_type == 2)]
    rows = []
    for _, g in done.iterrows():
        for side, opp in (("home", "away"), ("away", "home")):
            pf, pa = g[f"{side}_score"], g[f"{opp}_score"]
            rows.append(
                dict(
                    abbr=g[side],
                    Week=g.week,
                    Date=g.date.strftime("%b %d"),
                    Opponent=("vs " if side == "home" else "@ ") + g[opp],
                    Site="Home" if side == "home" else "Away",
                    Result="W" if pf > pa else "L" if pf < pa else "T",
                    PF=pf,
                    PA=pa,
                    _date=g.date,
                )
            )
    return pd.DataFrame(rows)


def power_rankings(games, directory):
    tg = team_game_rows(games)
    if tg.empty:
        return pd.DataFrame()
    s = tg.groupby("abbr").agg(
        GP=("Result", "size"),
        W=("Result", lambda x: (x == "W").sum()),
        L=("Result", lambda x: (x == "L").sum()),
        T=("Result", lambda x: (x == "T").sum()),
        PF=("PF", "mean"),
        PA=("PA", "mean"),
    )
    s["WinPct"] = (s.W + 0.5 * s["T"]) / s.GP
    s["Diff"] = s.PF - s.PA
    s = s.reset_index().merge(load_epa(season_year()), on="abbr", how="left")

    def z(col):
        sd = col.std(ddof=0)
        return (col - col.mean()) / sd if sd and sd > 0 else col * 0

    score = 0.35 * z(s.WinPct) + 0.45 * z(s.Diff)
    has_epa = s.epa_pg.notna().sum() >= 8
    if has_epa:
        score = 0.30 * z(s.WinPct) + 0.40 * z(s.Diff) + 0.30 * z(s.epa_pg.fillna(s.epa_pg.mean()))
    s["Power"] = (50 + 15 * score).clip(0, 100).round(1)
    s["name"] = s.abbr.map(lambda a: directory[a]["name"])
    s["color"] = s.abbr.map(lambda a: directory[a]["color"])
    s["logo"] = s.abbr.map(lambda a: directory[a]["logo"])
    s.attrs["has_epa"] = has_epa
