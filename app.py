def _get(url, params):
    try:
        r = requests.get(
            url,
            params=dict(params),
            timeout=10,
            headers={"User-Agent": "family-nfl-dashboard/1.0 (personal project)"},
        )
        r.raise_for_status()
        return r.json()
    except Exception:
        return None


@st.cache_data(ttl=25, show_spinner=False)
def fetch_short(url, params=()):
    """Cached ~25s so the 30s auto-refresh always gets fresh data."""
    return _get(url, params)


@st.cache_data(ttl=600, show_spinner=False)
def fetch_long(url, params=()):
    return _get(url, params)


def season_year():
    now = datetime.now(TZ)
    return now.year if now.month >= 3 else now.year - 1


def parse_events(data):
    rows = []
    for ev in (data or {}).get("events", []):
        try:
            comp = ev["competitions"][0]
            sides = {c["homeAway"]: c for c in comp["competitors"]}
            h, a = sides["home"], sides["away"]
            status = ev["status"]
            rows.append(
                dict(
                    id=ev["id"],
                    date=pd.to_datetime(ev["date"], utc=True).tz_convert(TZ),
                    season_type=(ev.get("season") or {}).get("type"),
                    week=(ev.get("week") or {}).get("number"),
                    state=status["type"]["state"],  # pre / in / post
                    detail=status["type"].get("shortDetail", ""),
                    period=status.get("period", 0),
                    clock=status.get("displayClock", ""),
                    home_id=h["team"]["id"],
                    home=h["team"]["abbreviation"],
                    home_name=h["team"]["displayName"],
                    home_color="#" + h["team"].get("color", "013369"),
                    home_logo=h["team"].get("logo", ""),
                    home_score=int(h.get("score") or 0),
                    away_id=a["team"]["id"],
                    away=a["team"]["abbreviation"],
                    away_name=a["team"]["displayName"],
                    away_color="#" + a["team"].get("color", "013369"),
                    away_logo=a["team"].get("logo", ""),
                    away_score=int(a.get("score") or 0),
                    venue_name=(comp.get("venue") or {}).get("fullName", ""),
                    venue_city=((comp.get("venue") or {}).get("address") or {}).get("city", ""),
                    indoor=bool((comp.get("venue") or {}).get("indoor", False)),
                    wx_text=(ev.get("weather") or {}).get("displayValue", "") or "",
                )
            )
        except Exception:
            continue
    return pd.DataFrame(rows)


