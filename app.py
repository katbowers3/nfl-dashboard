# Weather (Open-Meteo: free public forecast API, no key needed; ESPN as fallback)
# ----------------------------------------------------------------------------
WMO = {
    0: "☀️ Clear", 1: "🌤️ Mostly clear", 2: "⛅ Partly cloudy", 3: "☁️ Cloudy",
    45: "🌫️ Fog", 48: "🌫️ Fog", 51: "🌦️ Drizzle", 53: "🌦️ Drizzle", 55: "🌧️ Drizzle",
    61: "🌧️ Light rain", 63: "🌧️ Rain", 65: "🌧️ Heavy rain",
    71: "🌨️ Light snow", 73: "🌨️ Snow", 75: "❄️ Heavy snow",
    80: "🌦️ Showers", 81: "🌧️ Showers", 82: "⛈️ Heavy showers",
    95: "⛈️ Thunderstorms", 96: "⛈️ Thunderstorms", 99: "⛈️ Thunderstorms",
}


@st.cache_data(ttl=1800, show_spinner=False)
def city_hourly(city):
    """16-day hourly forecast for a stadium city (cached 30 min)."""
    geo = _get(
        "https://geocoding-api.open-meteo.com/v1/search",
        (("name", city), ("count", "5"), ("language", "en")),
    )
    results = [r for r in (geo or {}).get("results", []) if r.get("country_code") == "US"]
    if not results:
        return None
    fc = _get(
        "https://api.open-meteo.com/v1/forecast",
        (
            ("latitude", results[0]["latitude"]),
            ("longitude", results[0]["longitude"]),
            ("hourly", "temperature_2m,precipitation_probability,weathercode,windspeed_10m"),
            ("temperature_unit", "fahrenheit"),
            ("windspeed_unit", "mph"),
            ("timezone", str(TZ)),
            ("forecast_days", "16"),
        ),
    )
    return (fc or {}).get("hourly")


def game_weather(g):
    """One-line kickoff forecast for a game row."""
    if g.state == "post":
        return ""
    if g.indoor:
        return "🏟️ Indoor / dome"
    if g.venue_city and (g.date - pd.Timestamp.now(tz=TZ)).days <= 15:
        h = city_hourly(g.venue_city)
        if h:
            try:
                i = h["time"].index(g.date.round("h").strftime("%Y-%m-%dT%H:00"))
                desc = WMO.get(h["weathercode"][i], "Forecast")
                return (
                    f"{desc} · {h['temperature_2m'][i]:.0f}°F · "
                    f"{h['precipitation_probability'][i] or 0}% rain · {h['windspeed_10m'][i]:.0f} mph wind"
                )
            except Exception:
                pass
    if g.wx_text:
        return g.wx_text
    return "Forecast opens ~16 days before kickoff"


@st.cache_data(ttl=600, show_spinner="Loading season data...")
def _load_weeks(season, weeks):
    """Fetch regular-season weeks one at a time (in parallel). Cached 10 min."""
    from concurrent.futures import ThreadPoolExecutor

    def one(w):
        return _get(
            f"{ESPN}/scoreboard",
            (("week", str(w)), ("seasontype", "2"), ("dates", str(season))),
        )

    with ThreadPoolExecutor(max_workers=6) as ex:
        results = list(ex.map(one, weeks))
    if all(r is None for r in results):
        raise RuntimeError("ESPN scoreboard did not respond for any week")
    return results


def load_season_games():
    """All regular-season games (weeks 1-18). Current week is always fresh."""
    season = season_year()
    cur = fetch_short(f"{ESPN}/scoreboard")
    cur_type = ((cur or {}).get("season") or {}).get("type")
    cur_week = ((cur or {}).get("week") or {}).get("number")
    try:
        raw = _load_weeks(season, tuple(range(1, 19)))
    except Exception as e:
        st.session_state["feed_error"] = str(e)
        raw = []
    frames = [parse_events(r) for r in raw if r]
    if cur and cur_type == 2 and cur_week:
        frames = [f[f.week != cur_week] for f in frames if not f.empty]
        frames.append(parse_events(cur))
    frames = [f for f in frames if not f.empty]
    if not frames:
        return pd.DataFrame()
    games = pd.concat(frames, ignore_index=True).drop_duplicates("id", keep="last")
    return games


@st.cache_data(ttl=3600, show_spinner=False)
def load_epa(season):
    """Open nflverse team stats -> offensive EPA per game by team (or empty)."""
    try:
        df = pd.read_csv(NFLVERSE_TEAM_STATS.format(season=season))
        df = df[df.get("season_type", "REG") == "REG"] if "season_type" in df else df
        cols = [c for c in ("passing_epa", "rushing_epa") if c in df.columns]
        if not cols or "team" not in df.columns:
            return pd.DataFrame(columns=["abbr", "epa_pg"])
        df["off_epa"] = df[cols].sum(axis=1)
        out = df.groupby("team")["off_epa"].mean().reset_index()
        out.columns = ["abbr", "epa_pg"]
        out["abbr"] = out["abbr"].replace(ABBR_FIX)
        return out
    except Exception:
        return pd.DataFrame(columns=["abbr", "epa_pg"])


def load_injuries():
    data = fetch_long(f"{ESPN}/injuries")
    rows = []
    for t in (data or {}).get("injuries", []):
        for i in t.get("injuries", []):
            if str(i.get("status", "")).lower() == "active":
                continue  # feed lists healthy players too
            ath = i.get("athlete", {}) or {}
            rows.append(
                dict(
                    team=t.get("displayName"),
                    Player=ath.get("displayName"),
                    Pos=((ath.get("position") or {}).get("abbreviation")),
                    Status=i.get("status"),
                    Note=(i.get("shortComment") or "")[:90],
                )
            )
    return pd.DataFrame(rows)


